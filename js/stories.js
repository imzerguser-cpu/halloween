/** 장소(s: id·type·name)의 기본 괴담 — 장소id 이야기 → 유형 이야기 순. {장소} 는 장소 이름으로 바꾼다 */
window.HG_STORIES.defFor = function (s) {
  if (!s) return null;
  const S = window.HG_STORIES, d = S.byId[String(s.id || '').trim()] || S.byType[String(s.type || '').trim()];
  if (!d) return null;
  return { title: d.title, text: d.text.map((t) => t.replace(/\{장소\}/g, s.name || '여기')) };
};
